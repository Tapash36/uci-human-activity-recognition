#!/usr/bin/env python3
"""
evaluate_real_data.py — Real Smartphone Sensor CSV Evaluation Script (UCI HAR Capstone)

Loads a real recorded 50 Hz smartphone sensor CSV (3-axis accelerometer + 3-axis gyroscope),
applies the exact UCI HAR preprocessing pipeline (median filter, 20 Hz low-pass Butterworth
filter, 0.3 Hz Butterworth body/gravity separation, and 128-sample 50%-overlap windowing
into 128x9 tensors), runs the trained HAR model, and prints predicted activities along with
accuracy and a classification report if ground-truth labels are provided.

No synthetic or invented data is generated by this script.
"""

import argparse
import os
import sys
from pathlib import Path
from typing import Dict, List, Optional, Tuple

import joblib
import numpy as np
import pandas as pd
import torch
import torch.nn.functional as F
from scipy.signal import butter, filtfilt, medfilt
from sklearn.metrics import accuracy_score, classification_report, confusion_matrix, f1_score

BASE_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(BASE_DIR))
if (BASE_DIR / "HAR_API_Full_Package").exists():
    sys.path.insert(0, str(BASE_DIR / "HAR_API_Full_Package"))

from models import HAR_1DCNN, HAR_CNN_LSTM

ACTIVITY_MAP: Dict[int, str] = {
    1: "WALKING",
    2: "WALKING_UPSTAIRS",
    3: "WALKING_DOWNSTAIRS",
    4: "SITTING",
    5: "STANDING",
    6: "LAYING",
}
NAME_TO_ID: Dict[str, int] = {v: k for k, v in ACTIVITY_MAP.items()}


def preprocess_raw_imu_to_uci_channels(
    acc_xyz: np.ndarray,
    gyro_xyz: np.ndarray,
    fs: float = 50.0,
    acc_units: str = "auto",
    gyro_units: str = "rad",
) -> np.ndarray:
    """
    Convert continuous 50 Hz 3-axis total acceleration and 3-axis gyroscope readings
    into the 9 UCI HAR channels:
      [total_acc_x, total_acc_y, total_acc_z,
       body_acc_x,  body_acc_y,  body_acc_z,
       body_gyro_x, body_gyro_y, body_gyro_z]

    Follows Anguita et al. (2013):
      1. Convert units to standard gravity (g, where 1g = 9.80665 m/s^2) and rad/s.
      2. Apply 3-point median filter and 3rd-order 20 Hz low-pass Butterworth filter.
      3. Separate gravity component via 3rd-order 0.3 Hz low-pass Butterworth filter:
         body_acc = total_acc - gravity_acc.
    """
    acc = np.asarray(acc_xyz, dtype=np.float64).copy()
    gyro = np.asarray(gyro_xyz, dtype=np.float64).copy()

    # Unit conversion if recorded in m/s^2 instead of g
    if acc_units == "ms2" or (acc_units == "auto" and np.median(np.linalg.norm(acc, axis=1)) > 4.5):
        acc = acc / 9.80665

    if gyro_units == "deg":
        gyro = np.deg2rad(gyro)

    nyq = 0.5 * fs
    b_noise, a_noise = butter(3, min(20.0 / nyq, 0.99), btype="low")
    b_grav, a_grav = butter(3, min(0.3 / nyq, 0.99), btype="low")

    total_acc = np.zeros_like(acc)
    gravity_acc = np.zeros_like(acc)
    body_gyro = np.zeros_like(gyro)

    for axis in range(3):
        acc_med = medfilt(acc[:, axis], kernel_size=3)
        gyro_med = medfilt(gyro[:, axis], kernel_size=3)
        if len(acc_med) > 15:
            total_acc[:, axis] = filtfilt(b_noise, a_noise, acc_med)
            gravity_acc[:, axis] = filtfilt(b_grav, a_grav, total_acc[:, axis])
            body_gyro[:, axis] = filtfilt(b_noise, a_noise, gyro_med)
        else:
            total_acc[:, axis] = acc_med
            gravity_acc[:, axis] = np.mean(acc_med)
            body_gyro[:, axis] = gyro_med

    body_acc = total_acc - gravity_acc
    channels_9 = np.hstack([total_acc, body_acc, body_gyro]).astype(np.float32)
    return channels_9


def window_signals(
    channels_9: np.ndarray,
    window_size: int = 128,
    step_size: int = 64,
    sample_labels: Optional[np.ndarray] = None,
) -> Tuple[np.ndarray, Optional[np.ndarray], List[Tuple[int, int]]]:
    """
    Slice continuous (T, 9) array into (N_windows, 128, 9) windows with 50% overlap (step=64).
    If sample-level labels are provided, assigns the majority label in each 128-sample window.
    """
    n_samples = len(channels_9)
    if n_samples < window_size:
        raise ValueError(
            f"Input CSV has only {n_samples} rows, but at least {window_size} rows (2.56s at 50 Hz) are required."
        )

    windows = []
    win_labels = []
    spans = []

    for start in range(0, n_samples - window_size + 1, step_size):
        end = start + window_size
        windows.append(channels_9[start:end])
        spans.append((start, end))
        if sample_labels is not None:
            slice_lbls = sample_labels[start:end]
            vals, counts = np.unique(slice_lbls, return_counts=True)
            win_labels.append(vals[np.argmax(counts)])

    X_win = np.stack(windows, axis=0).astype(np.float32)
    y_win = np.array(win_labels) if sample_labels is not None else None
    return X_win, y_win, spans


def parse_columns(df: pd.DataFrame) -> Tuple[np.ndarray, np.ndarray, Optional[np.ndarray]]:
    """
    Detect accelerometer, gyroscope, and optional activity label columns in the user's CSV.
    Also supports pre-separated 9-channel CSVs.
    """
    cols_lower = {c.lower().strip(): c for c in df.columns}

    # Check if all 9 UCI channels are already present
    uci_9 = [
        "total_acc_x", "total_acc_y", "total_acc_z",
        "body_acc_x", "body_acc_y", "body_acc_z",
        "body_gyro_x", "body_gyro_y", "body_gyro_z",
    ]
    if all(k in cols_lower for k in uci_9):
        ch9 = df[[cols_lower[k] for k in uci_9]].values.astype(np.float32)
        lbl = _extract_label_column(df, cols_lower)
        return ch9, np.empty((0, 3)), lbl

    acc_candidates = [
        ("acc_x", "acc_y", "acc_z"),
        ("ax", "ay", "az"),
        ("accelerometer_x", "accelerometer_y", "accelerometer_z"),
        ("total_acc_x", "total_acc_y", "total_acc_z"),
    ]
    gyro_candidates = [
        ("gyro_x", "gyro_y", "gyro_z"),
        ("gx", "gy", "gz"),
        ("gyroscope_x", "gyroscope_y", "gyroscope_z"),
        ("body_gyro_x", "body_gyro_y", "body_gyro_z"),
    ]

    acc_cols = None
    for triplet in acc_candidates:
        if all(k in cols_lower for k in triplet):
            acc_cols = [cols_lower[k] for k in triplet]
            break

    gyro_cols = None
    for triplet in gyro_candidates:
        if all(k in cols_lower for k in triplet):
            gyro_cols = [cols_lower[k] for k in triplet]
            break

    if acc_cols is None or gyro_cols is None:
        raise ValueError(
            f"Could not find 3-axis accelerometer and gyroscope columns in CSV. Found columns: {list(df.columns)}. "
            "Expected columns: acc_x, acc_y, acc_z, gyro_x, gyro_y, gyro_z"
        )

    acc_xyz = df[acc_cols].values.astype(np.float64)
    gyro_xyz = df[gyro_cols].values.astype(np.float64)
    lbl = _extract_label_column(df, cols_lower)
    return acc_xyz, gyro_xyz, lbl


def _extract_label_column(df: pd.DataFrame, cols_lower: Dict[str, str]) -> Optional[np.ndarray]:
    for cand in ["activity", "label", "activity_id", "activity_name", "class"]:
        if cand in cols_lower:
            raw = df[cols_lower[cand]].values
            return normalize_labels(raw)
    return None


def normalize_labels(raw_labels: np.ndarray) -> np.ndarray:
    norm = []
    for item in raw_labels:
        if isinstance(item, (int, np.integer)) or (isinstance(item, str) and item.strip().isdigit()):
            val = int(item)
            norm.append(ACTIVITY_MAP.get(val, str(val)))
        else:
            s = str(item).strip().upper().replace(" ", "_")
            norm.append(s)
    return np.array(norm)


def load_best_1dcnn_model() -> Tuple[HAR_1DCNN, Optional[np.ndarray], Optional[np.ndarray]]:
    model = HAR_1DCNN(in_channels=9, num_classes=6)
    search_dirs = [BASE_DIR, BASE_DIR / "HAR_API_Full_Package"]

    clean_weights = None
    orig_weights = None
    pipeline_path = None
    for d in search_dirs:
        if (d / "har_1dcnn_clean.pth").exists():
            clean_weights = d / "har_1dcnn_clean.pth"
        if (d / "har_1dcnn_weights.pth").exists():
            orig_weights = d / "har_1dcnn_weights.pth"
        if (d / "best_har_pipeline.joblib").exists():
            pipeline_path = d / "best_har_pipeline.joblib"

    mean_c, std_c = None, None
    if clean_weights is not None and pipeline_path is not None:
        model.load_state_dict(torch.load(str(clean_weights), map_location="cpu", weights_only=True))
        pipe = joblib.load(str(pipeline_path))
        mean_c = pipe.get("cnn1d_mean")
        std_c = pipe.get("cnn1d_std")
    elif orig_weights is not None:
        model.load_state_dict(torch.load(str(orig_weights), map_location="cpu", weights_only=True))
    else:
        raise FileNotFoundError("Could not find trained HAR_1DCNN weights (har_1dcnn_clean.pth or har_1dcnn_weights.pth).")

    model.eval()
    return model, mean_c, std_c


def main():
    parser = argparse.ArgumentParser(
        description="Evaluate recorded 50 Hz smartphone IMU CSV data using the trained UCI HAR model."
    )
    parser.add_argument("--csv", type=str, required=True, help="Path to recorded smartphone CSV file (50 Hz).")
    parser.add_argument(
        "--labels",
        type=str,
        default=None,
        help="Optional path to ground-truth labels file (one label per window or per row). If omitted, checks CSV for an 'activity'/'label' column.",
    )
    parser.add_argument("--fs", type=float, default=50.0, help="Sampling rate in Hz (default: 50.0).")
    parser.add_argument(
        "--units",
        type=str,
        choices=["auto", "g", "ms2"],
        default="auto",
        help="Accelerometer units: 'g', 'ms2' (m/s^2), or 'auto' (default).",
    )
    parser.add_argument(
        "--gyro-units",
        type=str,
        choices=["rad", "deg"],
        default="rad",
        help="Gyroscope units: 'rad' (rad/s, default) or 'deg' (deg/s).",
    )
    parser.add_argument("--window", type=int, default=128, help="Sliding window length in samples (default: 128).")
    parser.add_argument("--step", type=int, default=64, help="Sliding window step in samples (default: 64, 50%% overlap).")
    args = parser.parse_args()

    csv_path = Path(args.csv)
    if not csv_path.exists():
        print(f"[ERROR] CSV file not found: {csv_path}", file=sys.stderr)
        sys.exit(1)

    df = pd.read_csv(csv_path)
    acc_or_ch9, gyro_xyz, csv_labels = parse_columns(df)

    if gyro_xyz.size == 0 and acc_or_ch9.shape[1] == 9:
        channels_9 = acc_or_ch9
    else:
        channels_9 = preprocess_raw_imu_to_uci_channels(
            acc_or_ch9, gyro_xyz, fs=args.fs, acc_units=args.units, gyro_units=args.gyro_units
        )

    X_win, y_win, spans = window_signals(
        channels_9, window_size=args.window, step_size=args.step, sample_labels=csv_labels
    )

    # Load external labels file if provided
    if args.labels is not None:
        lbl_path = Path(args.labels)
        if not lbl_path.exists():
            print(f"[ERROR] Labels file not found: {lbl_path}", file=sys.stderr)
            sys.exit(1)
        lbl_df = pd.read_csv(lbl_path, header=None)
        raw_ext = lbl_df.iloc[:, -1].values
        # Drop header row if string 'activity' or 'label'
        if len(raw_ext) > 0 and str(raw_ext[0]).strip().lower() in {"activity", "label", "activity_id", "activity_name"}:
            raw_ext = raw_ext[1:]
        norm_ext = normalize_labels(raw_ext)
        if len(norm_ext) == len(X_win):
            y_win = norm_ext
        elif len(norm_ext) == len(channels_9):
            _, y_win, _ = window_signals(channels_9, window_size=args.window, step_size=args.step, sample_labels=norm_ext)
        else:
            raise ValueError(
                f"Labels file length ({len(norm_ext)}) does not match number of windows ({len(X_win)}) or rows ({len(channels_9)})."
            )

    model, mean_c, std_c = load_best_1dcnn_model()
    X_in = X_win.copy()
    if mean_c is not None and std_c is not None:
        X_in = (X_in - mean_c.reshape(1, 1, 9)) / std_c.reshape(1, 1, 9)

    X_tensor = torch.from_numpy(np.transpose(X_in, (0, 2, 1))).float()
    with torch.no_grad():
        logits = model(X_tensor)
        probs = F.softmax(logits, dim=1).numpy()
        pred_ids = probs.argmax(axis=1) + 1
        confs = probs.max(axis=1) * 100.0

    pred_names = np.array([ACTIVITY_MAP[i] for i in pred_ids])

    print("=" * 76)
    print(f"UCI HAR Real Phone Data Evaluation | File: {csv_path.name}")
    print(f"Total Rows: {len(channels_9)} (@ {args.fs:.1f} Hz) -> Windows (128x9, step={args.step}): {len(X_win)}")
    print("=" * 76)
    print(f"{'Win #':>5} | {'Samples':>13} | {'Time (s)':>13} | {'Predicted Activity':<20} | {'Conf (%)':>8}")
    print("-" * 76)
    for idx, ((s, e), pname, conf) in enumerate(zip(spans, pred_names, confs), start=1):
        t_start = s / args.fs
        t_end = e / args.fs
        print(f"{idx:5d} | {f'{s}-{e}':>13} | {f'{t_start:5.2f}-{t_end:5.2f}s':>13} | {pname:<20} | {conf:7.2f}%")

    print("\n--- Predicted Activity Distribution ---")
    vals, counts = np.unique(pred_names, return_counts=True)
    for v, c in zip(vals, counts):
        print(f"  {v:<20}: {c:4d} windows ({c / len(pred_names) * 100:5.1f}%)")

    if y_win is not None:
        acc = accuracy_score(y_win, pred_names) * 100.0
        mf1 = f1_score(y_win, pred_names, average="macro", zero_division=0) * 100.0
        print("\n" + "=" * 76)
        print(f"GROUND-TRUTH EVALUATION | Accuracy: {acc:.2f}% | Macro F1: {mf1:.2f}%")
        print("=" * 76)
        print(classification_report(y_win, pred_names, zero_division=0))


if __name__ == "__main__":
    main()
